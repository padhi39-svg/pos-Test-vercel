import { getTableName } from 'drizzle-orm'
import * as schema from './schema'
import { rawAll } from './raw'

export interface ColumnInfo {
  name: string
  dataType: string
  columnType: string
  notNull: boolean
  primary: boolean
  hasDefault: boolean
  isUnique: boolean
  generatedIdentity: string | null
}

export interface TableSchema {
  tableName: string
  columns: ColumnInfo[]
}

export interface SchemaDiff {
  ok: boolean
  missingTables: { tableName: string; columns: ColumnInfo[] }[]
  missingColumns: { table: string; columns: ColumnInfo[] }[]
  extraTables: string[]
  errors: string[]
  schemaTables: TableSchema[]
  dbTables: { tableName: string; columns: string[] }[]
}

export function drizzleTypeToPg(col: ColumnInfo): string {
  switch (col.columnType) {
    case 'PgInteger':
    case 'PgSerial':
      return 'integer'
    case 'PgText':
      return 'text'
    case 'PgDoublePrecision':
      return 'double precision'
    case 'PgTimestampString':
    case 'PgTimestamp':
      return 'timestamp'
    case 'PgDateString':
      return 'date'
    default:
      return 'text'
  }
}

export function getSchemaTables(): TableSchema[] {
  const results: TableSchema[] = []

  for (const key of Object.keys(schema)) {
    const table = (schema as any)[key]
    if (!table || typeof table !== 'object') continue
    if (!table[Symbol.for('drizzle:Name')]) continue

    const tableName = getTableName(table)
    if (!tableName || tableName === 'undefined') continue

    const columns = table[Symbol.for('drizzle:Columns')]
    if (!columns) continue

    const cols: ColumnInfo[] = []
    for (const colKey of Object.keys(columns)) {
      const col = columns[colKey]
      cols.push({
        name: col.name,
        dataType: col.dataType,
        columnType: col.columnType,
        notNull: !!col.notNull,
        primary: !!col.primary,
        hasDefault: !!col.hasDefault,
        isUnique: !!col.isUnique,
        generatedIdentity: col.generatedIdentity?.type || null,
      })
    }

    results.push({ tableName, columns: cols })
  }

  return results
}

export async function checkSchema(): Promise<SchemaDiff> {
  const diff: SchemaDiff = {
    ok: true,
    missingTables: [],
    missingColumns: [],
    extraTables: [],
    errors: [],
    schemaTables: [],
    dbTables: [],
  }

  let schemaTables: TableSchema[]
  try {
    schemaTables = getSchemaTables()
    diff.schemaTables = schemaTables
  } catch (e: any) {
    diff.errors.push(`Gagal baca schema: ${e.message}`)
    diff.ok = false
    return diff
  }

  let dbTables: string[]
  try {
    const result = await rawAll<{ table_name: string }>(
      `SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' AND table_type = 'BASE TABLE'`
    )
    dbTables = result.map(r => r.table_name)
  } catch (e: any) {
    diff.errors.push(`Gagal query database: ${e.message}`)
    diff.ok = false
    return diff
  }

  for (const st of schemaTables) {
    const exists = dbTables.includes(st.tableName)

    if (!exists) {
      diff.missingTables.push(st)
      diff.ok = false
      continue
    }

    let dbCols: string[]
    try {
      const result = await rawAll<{ column_name: string }>(
        `SELECT column_name FROM information_schema.columns WHERE table_schema = 'public' AND table_name = $1`,
        [st.tableName]
      )
      dbCols = result.map(r => r.column_name)
    } catch (e: any) {
      diff.errors.push(`Gagal cek kolom ${st.tableName}: ${e.message}`)
      diff.ok = false
      continue
    }

    diff.dbTables.push({ tableName: st.tableName, columns: dbCols })

    const missing: ColumnInfo[] = []
    for (const col of st.columns) {
      if (!dbCols.includes(col.name)) {
        missing.push(col)
      }
    }

    if (missing.length > 0) {
      diff.missingColumns.push({ table: st.tableName, columns: missing })
      diff.ok = false
    }
  }

  for (const dbTable of dbTables) {
    const found = schemaTables.some(st => st.tableName === dbTable)
    if (!found) {
      diff.extraTables.push(dbTable)
    }
  }

  return diff
}

export function generateCreateTable(table: TableSchema): string {
  const colDefs: string[] = []
  for (const col of table.columns) {
    let def = `  "${col.name}" ${drizzleTypeToPg(col)}`

    if (col.generatedIdentity === 'always') {
      def += ' GENERATED ALWAYS AS IDENTITY'
    } else if (col.generatedIdentity === 'byDefault') {
      def += ' GENERATED BY DEFAULT AS IDENTITY'
    }

    if (col.notNull) def += ' NOT NULL'
    if (col.primary) def += ' PRIMARY KEY'

    colDefs.push(def)
  }

  return `CREATE TABLE IF NOT EXISTS "${table.tableName}" (\n${colDefs.join(',\n')}\n);`
}

export function generateAlterColumn(tableName: string, col: ColumnInfo): string {
  let def = `ALTER TABLE "${tableName}" ADD COLUMN IF NOT EXISTS "${col.name}" ${drizzleTypeToPg(col)}`

  if (col.generatedIdentity === 'always') {
    def += ' GENERATED ALWAYS AS IDENTITY'
  } else if (col.generatedIdentity === 'byDefault') {
    def += ' GENERATED BY DEFAULT AS IDENTITY'
  }

  if (col.notNull) def += ' NOT NULL'

  return def + ';'
}

export function formatDiff(diff: SchemaDiff): string {
  const lines: string[] = []
  lines.push('=== Database Schema Check ===')
  lines.push('')

  if (diff.errors.length > 0) {
    lines.push(`ERRORS (${diff.errors.length}):`)
    for (const err of diff.errors) lines.push(`  ! ${err}`)
    lines.push('')
  }

  if (diff.missingTables.length > 0) {
    lines.push(`MISSING TABLES (${diff.missingTables.length}):`)
    for (const t of diff.missingTables) {
      lines.push(`  - "${t.tableName}" (${t.columns.length} columns)`)
    }
    lines.push('')
  }

  if (diff.missingColumns.length > 0) {
    lines.push(`MISSING COLUMNS (${diff.missingColumns.length} tables affected):`)
    for (const mc of diff.missingColumns) {
      lines.push(`  "${mc.table}":`)
      for (const col of mc.columns) {
        lines.push(`    - "${col.name}" (${col.columnType})`)
      }
    }
    lines.push('')
  }

  if (diff.extraTables.length > 0) {
    lines.push(`EXTRA TABLES (di DB tapi tidak di schema) (${diff.extraTables.length}):`)
    for (const t of diff.extraTables) {
      lines.push(`  + "${t}"`)
    }
    lines.push('')
  }

  lines.push(`Status: ${diff.ok ? 'OK - Schema sesuai database' : 'ADA PERBEDAAN -但ukan koreksi otomatis dengan sync'}`)
  lines.push(`Schema tables: ${diff.schemaTables.length}, DB tables: ${diff.dbTables.length + diff.missingTables.length}`)

  return lines.join('\n')
}
