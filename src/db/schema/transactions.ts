import { pgTable, text, integer, doublePrecision, index, timestamp, date } from 'drizzle-orm/pg-core'
import { sql } from 'drizzle-orm'
import { masterBarang } from './barang'
import { masterCustomer } from './customer-supplier'

export const transactions = pgTable('transactions', {
  id: integer('id').primaryKey().generatedAlwaysAsIdentity(),
  transactionNumber: text('transaction_number').unique().notNull(),
  customerId: integer('customer_id').references(() => masterCustomer.id),
  customerName: text('customer_name'),
  customerCode: text('customer_code'),
  subtotal: doublePrecision('subtotal').notNull(),
  discountPercent: doublePrecision('discount_percent').default(0),
  discountAmount: doublePrecision('discount_amount').default(0),
  serviceChargePercent: doublePrecision('service_charge_percent').default(0),
  serviceChargeAmount: doublePrecision('service_charge_amount').default(0),
  total: doublePrecision('total').notNull(),
  paymentMethod: text('payment_method').default('cash'),
  fakturPajak: text('faktur_pajak'),
  paymentAmount: doublePrecision('payment_amount'),
  changeAmount: doublePrecision('change_amount').default(0),
  status: text('status').default('completed'),
  cardNumber: text('card_number'),
  totalDiscount: doublePrecision('total_discount').default(0),
  void: integer('void').default(0),
  transactionType: integer('transaction_type').default(1),
  isReturn: integer('is_return').default(0),
  periodId: integer('period_id'),
  createdAt: timestamp('created_at', { mode: 'string' }).default(sql`CURRENT_TIMESTAMP`),
  updatedAt: timestamp('updated_at', { mode: 'string' }).default(sql`CURRENT_TIMESTAMP`),
}, (t) => [
  index('idx_transactions_number').on(t.transactionNumber),
  index('idx_transactions_date').on(t.createdAt),
  index('idx_transactions_void').on(t.void),
  index('idx_transactions_type').on(t.transactionType),
])

export const transactionItems = pgTable('transaction_items', {
  id: integer('id').primaryKey().generatedAlwaysAsIdentity(),
  transactionId: integer('transaction_id').notNull().references(() => transactions.id, { onDelete: 'cascade' }),
  barangId: integer('barang_id').notNull().references(() => masterBarang.id),
  barangCode: text('barang_code').notNull(),
  barangName: text('barang_name').notNull(),
  quantity: doublePrecision('quantity').notNull(),
  unitName: text('unit_name').default('PCS'),
  unitRatio: integer('unit_ratio').default(1),
  unitPrice: doublePrecision('unit_price').notNull(),
  discountPercent: doublePrecision('discount_percent').default(0),
  discountAmount: doublePrecision('discount_amount').default(0),
  totalPrice: doublePrecision('total_price').notNull(),
  unitPriceIncludeTax: doublePrecision('unit_price_include_tax'),
  paketId: integer('paket_id'),
  disc1Percent: doublePrecision('disc1_percent').default(0),
  disc1Amount: doublePrecision('disc1_amount').default(0),
  disc2Percent: doublePrecision('disc2_percent').default(0),
  disc2Amount: doublePrecision('disc2_amount').default(0),
  disc3Percent: doublePrecision('disc3_percent').default(0),
  disc3Amount: doublePrecision('disc3_amount').default(0),
  grossAmount: doublePrecision('gross_amount').default(0),
  netAmount: doublePrecision('net_amount').default(0),
  discNominal: doublePrecision('disc_nominal').default(0),
  bonusBarangId: integer('bonus_barang_id'),
  bonusName: text('bonus_name'),
  bonusQty: doublePrecision('bonus_qty').default(0),
  bonusUnit: text('bonus_unit'),
  bonusUnitRatio: doublePrecision('bonus_unit_ratio').default(1),
  createdAt: timestamp('created_at', { mode: 'string' }).default(sql`CURRENT_TIMESTAMP`),
}, (t) => [index('idx_transaction_items_transaction').on(t.transactionId)])

export const transactionPayments = pgTable('transaction_payments', {
  id: integer('id').primaryKey().generatedAlwaysAsIdentity(),
  transactionId: integer('transaction_id').notNull().references(() => transactions.id, { onDelete: 'cascade' }),
  method: text('method').notNull(),
  amount: doublePrecision('amount').notNull(),
  bankId: integer('bank_id'),
  cardNumber: text('card_number'),
  notes: text('notes'),
  changeAmount: doublePrecision('change_amount').default(0),
  accountId: integer('account_id'),
  createdAt: timestamp('created_at', { mode: 'string' }).default(sql`CURRENT_TIMESTAMP`),
}, (t) => [
  index('idx_transaction_payments_transaction').on(t.transactionId),
  index('idx_transaction_payments_method').on(t.method),
])
